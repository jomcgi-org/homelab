#!/usr/bin/env bash
set -euo pipefail

# External rootpaths contain ../, which Go's runfiles resolver rejects even
# in an absolute path. Resolve every input before invoking the pinned test.
guard="$(realpath "$1")"
_TEST_REQUIREMENTS="$(realpath "$2")"
_TEST_MANIFEST="$(realpath "$3")"
_TEST_MANIFEST_GENERATOR_HASH="$(realpath "$4")"
export _TEST_REQUIREMENTS _TEST_MANIFEST _TEST_MANIFEST_GENERATOR_HASH

"$guard" -test.v
echo 'PASS: pinned manifest guard accepts generated bytes'

cp "$_TEST_REQUIREMENTS" "$TEST_TMPDIR/stale.txt"
printf '\n# deliberately changed lock fixture\n' >>"$TEST_TMPDIR/stale.txt"
if _TEST_REQUIREMENTS="$TEST_TMPDIR/stale.txt" "$guard" -test.v >"$TEST_TMPDIR/lock.log" 2>&1; then
	echo 'FAIL: pinned manifest guard accepted a stale lock' >&2
	exit 1
fi
cat "$TEST_TMPDIR/lock.log"
grep -q 'is out-of-date' "$TEST_TMPDIR/lock.log"
echo 'PASS: pinned manifest guard rejects lock drift'

# Match the pinned generator's nested pip_repository.name field.
sed 's/^    name: pip$/    name: stale/' "$_TEST_MANIFEST" >"$TEST_TMPDIR/stale.yaml"
if cmp -s "$_TEST_MANIFEST" "$TEST_TMPDIR/stale.yaml"; then
	echo 'FAIL: stale manifest fixture did not change the generated manifest' >&2
	exit 1
fi
if _TEST_MANIFEST="$TEST_TMPDIR/stale.yaml" "$guard" -test.v >"$TEST_TMPDIR/manifest.log" 2>&1; then
	echo 'FAIL: pinned manifest guard accepted a stale manifest' >&2
	exit 1
fi
cat "$TEST_TMPDIR/manifest.log"
grep -q 'is out-of-date' "$TEST_TMPDIR/manifest.log"
echo 'PASS: pinned manifest guard rejects manifest drift'
