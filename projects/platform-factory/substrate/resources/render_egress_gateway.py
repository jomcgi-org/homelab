#!/usr/bin/env python3
"""Generate the opt-in gateway patch from the private receiver gateway configuration."""

import sys
from pathlib import Path

import yaml


class Literal(str):
    pass


class Dumper(yaml.SafeDumper):
    pass


Dumper.add_representer(
    Literal,
    lambda dumper, data: dumper.represent_scalar(
        "tag:yaml.org,2002:str", data, style="|"
    ),
)

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "atenet-egress-config.yaml"
PILOT = HERE / "egress-scan"
POLICY = PILOT / "gateway-policy.yaml"
# The scan of HTTPS destinations that the gateway terminates (HOME-938).
TLS_POLICY = PILOT / "gateway-policy-tls.yaml"
PATCH = PILOT / "gateway-patch.yaml"


def _listener(config, protocol):
    (listener,) = (
        listener
        for bind in config["binds"]
        if bind.get("mode") == "internal"
        for listener in bind["listeners"]
        if listener["protocol"] == protocol
    )
    return listener


def _add_scan(route, scanner_policy):
    policies = route["policies"]
    assert "substrateEgress" in policies and "extAuthz" not in policies
    policies["extAuthz"] = scanner_policy


def gateway_patch(source, scanner_policy, tls_policy=None):
    config = yaml.safe_load(source)
    (route,) = _listener(config, "HTTP")["routes"]
    _add_scan(route, scanner_policy)
    if tls_policy:
        # The unnamed catch-all route of the terminated HTTPS listener: the
        # named routes go to in-cluster services.
        (route,) = (r for r in _listener(config, "HTTPS")["routes"] if "name" not in r)
        _add_scan(route, tls_policy)
    return {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {
            "name": "atenet-egress-guard-config",
            "namespace": "ate-system",
            "annotations": {"argocd.argoproj.io/sync-wave": "1"},
        },
        "data": {
            "config.yaml": Literal(yaml.safe_dump(config, sort_keys=False, width=1000))
        },
    }


if __name__ == "__main__":
    text = "# Generated by render_egress_gateway.py.\n" + yaml.dump(
        gateway_patch(
            SOURCE.read_text(),
            yaml.safe_load(POLICY.read_text()),
            yaml.safe_load(TLS_POLICY.read_text()),
        ),
        Dumper=Dumper,
        sort_keys=False,
    )
    if sys.argv[1:] == ["--check"]:
        if yaml.safe_load(PATCH.read_text()) != yaml.safe_load(text):
            raise SystemExit("egress scan gateway patch needs regeneration")
    elif not sys.argv[1:]:
        PATCH.write_text(text)
    else:
        raise SystemExit("usage: render_egress_gateway.py [--check]")
