"""Do not spend another learning turn on unchanged, already-empty evidence.

The existing routine lease owns collection and its server-pinned input. One
report-only diagnosis is routed to the existing program or active task. No
receipt, issue, breaker reset or execution recovery is created here.
"""

import copy
from datetime import datetime, timezone
import json
import os
import re

from sqlalchemy import text
from sqlmodel import Session, select

from core.db import get_engine
from core.jsonio import dumps
from factory.orchestration import learning, retro
from factory.orchestration.factory_models import FactoryAudit, FactoryReceipt

JOB = "factory-retro-daily"
ACTION = "learning_diagnosis_required"
ACTOR = "factory:learning-inputs"
VOLATILE = {
    "observed_at",
    "captured_at",
    "snapshot_age_seconds",
    "age_seconds",
    "age_days",
    "generated_at",
    "outcomes_and_cost_as_of",
    "reconciled_at",
}


def enabled():
    return (
        os.environ.get("FACTORY_LEARNING_INPUT_DEDUP_ENABLED", "false") == "true"
        and learning.enabled()
    )


def _stable(value):
    if isinstance(value, dict):
        return {k: _stable(v) for k, v in value.items() if k not in VOLATILE}
    if isinstance(value, list):
        # Query order and the diagnostic generated by this gate are not new
        # research evidence. Original record identity/timestamps are retained.
        values = [
            _stable(v)
            for v in value
            if not isinstance(v, dict) or v.get("action") != ACTION
        ]
        return sorted(values, key=lambda v: json.dumps(v, sort_keys=True, default=str))
    if isinstance(value, datetime):
        return value.isoformat()
    return value


def fingerprint(data, head, instructions):
    if not re.fullmatch(r"[0-9a-f]{40}", head or ""):
        raise ValueError("learning_input_head_unavailable")
    optimizer = data.get("optimizer") or {}
    observed = retro._utc_time(optimizer.get("outcomes_and_cost_as_of"))
    if optimizer.get("outcomes_and_cost_as_of") and observed is None:
        raise ValueError("learning_input_observation_unavailable")
    verdict = retro.optimizer_evidence(optimizer, observed) if observed else {}
    return learning._sha(
        {
            "version": 1,
            "head": head,
            "instructions": instructions,
            "data": _stable(data),
            # Clock ticks are not evidence, but reaching the existing bounded
            # settlement horizon changes the conclusion even without new rows.
            "optimizer_phase": {
                k: verdict[k] for k in ("status", "reason") if k in verdict
            },
        }
    )


def _save(db, payload):
    table = learning._table(db, "claude_agent", "routine_jobs")
    value = (
        ":payload"
        if db.get_bind().dialect.name == "sqlite"
        else "CAST(:payload AS JSONB)"
    )
    db.execute(
        text(f"UPDATE {table} SET payload={value} WHERE name=:name"),
        {"payload": json.dumps(payload), "name": JOB},
    )


def _diagnose(db, payload, fingerprint_value, previous):
    marker = "factory-learning:unchanged:" + fingerprint_value
    exists = db.exec(
        select(FactoryAudit.id).where(
            FactoryAudit.action == ACTION,
            FactoryAudit.detail_json.contains(
                f'"marker":{dumps(marker)}', autoescape=True
            ),
        )
    ).first()
    if exists:
        return
    # A paused/escalated/queued owner still owns the program. Do not create a
    # second executor merely because its current node is not running.
    owners = db.exec(
        select(FactoryReceipt).where(
            FactoryReceipt.repo == learning.REPO,
            FactoryReceipt.issue_number == 6781,
            FactoryReceipt.state.in_(
                ("queued", "admitted", "uncertain", "landing", "escalated")
            ),
        )
    ).all()
    owner = owners[0] if len(owners) == 1 else None
    detail = {
        "marker": marker,
        "input_sha256": fingerprint_value,
        "issue_number": 6781,
        "reason": "A completed empty retrospective would repeat unchanged input. Diagnose collection coverage or the reporting contract before proposing a repair. An empty finding list is not evidence of infrastructure health or failure.",
        "source": previous,
        "owner_receipt_id": owner.id if owner else None,
        "state": "existing_owner" if owners else "bounded_diagnosis_queued",
        "ambiguous_owners": len(owners) > 1,
    }
    if not owners:
        # The retained unique routine name is the replay fence, including an
        # unknown earlier diagnosis. Normal drainer quota/permit guards apply.
        table = learning._table(db, "claude_agent", "routine_jobs")
        packet = {
            "program_issue": 6781,
            "input_sha256": fingerprint_value,
            "last_empty_evidence": previous,
            "reason": detail["reason"],
        }
        next_payload = {
            "model": "astra",
            "repo": learning.REPO,
            "branch": "main",
            "learning_stage": "diagnose",
            "learning_evidence": packet,
            "prompt": "Diagnose repeated empty learning for existing program #6781",
        }
        value = (
            ":payload"
            if db.get_bind().dialect.name == "sqlite"
            else "CAST(:payload AS JSONB)"
        )
        db.execute(
            text(
                f"INSERT INTO {table} (name,routine_kind,interval_secs,next_run_at,payload,created_by) VALUES (:name,'qwen-drain',NULL,:now,{value},:actor) ON CONFLICT (name) DO NOTHING"
            ),
            {
                "name": marker,
                "now": datetime.now(timezone.utc),
                "payload": json.dumps(next_payload),
                "actor": ACTOR,
            },
        )
    db.add(
        FactoryAudit(
            actor=ACTOR,
            action=ACTION,
            task_id=owner.task_id if owner else None,
            detail_json=dumps(detail),
        )
    )


def prepare(db, name, holder, data, head):
    from agent.api import lock_claim

    if not enabled() or name != JOB or not holder or not lock_claim(db, name, holder):
        raise ValueError("learning_input_owner_changed_or_disabled")
    table = learning._table(db, "claude_agent", "routine_jobs")
    rows = learning._rows(
        db, f"SELECT payload FROM {table} WHERE name=:name", {"name": name}
    )
    payload = learning._json(rows[0]["payload"])
    if learning.validate_payload(payload) != "evidence":
        raise ValueError("learning_input_stage_changed")
    instructions = learning.prompt(payload)
    identity = fingerprint(data, head, instructions)
    previous = payload.get("learning_last_evidence") or {}
    if (
        previous.get("input_sha256") == identity
        and previous.get("disposition") == "no_finding"
    ):
        # Verify the exact saved completed output before treating it as empty.
        source = learning._turn(db, previous["session_id"], previous["turn_seq"])
        output = learning._output(source["result_text"])
        if output != {"findings": []} or learning._sha(output) != previous.get(
            "output_sha256"
        ):
            raise ValueError("learning_input_prior_result_changed")
        _diagnose(db, payload, identity, previous)
        payload["learning_input_observation"] = {
            "input_sha256": identity,
            "disposition": "no_new_evidence",
            "source_session_id": previous["session_id"],
        }
        _save(db, payload)
        return {"skip": True, "input_sha256": identity, "reason": "no_new_evidence"}
    payload["learning_input"] = {
        "input_sha256": identity,
        "head_sha": head,
        "holder": holder,
    }
    _save(db, payload)
    return {
        "skip": False,
        "input_sha256": identity,
        "prompt": retro.render_factory_retro_prompt(
            instructions,
            copy.deepcopy(data),
            now=retro._utc_time(
                (data.get("optimizer") or {}).get("outcomes_and_cost_as_of")
            ),
        ),
    }


def prepare_job(name, holder):
    from factory.orchestration.factory_conductor import github_get

    with Session(get_engine()) as db:
        data = retro.load_retro_data(db)
    # A fresh code head is part of the evidence identity. Failure never means
    # unchanged. Let normal failure accounting record unavailable observation.
    head = github_get(learning.REPO, "commits/main").get("sha")
    with Session(get_engine()) as db, db.begin():
        return prepare(db, name, holder, data, head)
