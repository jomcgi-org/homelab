"""Generate the TypeScript contract the friends browser UI compiles against.

The output is committed at ``web/grimoire/src/api/schema.ts`` and
``browser_api_schema_test.py`` fails when it is stale. A change to a response
model then breaks the UI's typecheck in the same pull request, before a player
meets it. Only browser-routed paths are emitted (see ``browser_lane.py``).

Regenerate from ``projects/monolith``::

    python -m grimoire.browser_api_schema > web/grimoire/src/api/schema.ts
"""

from __future__ import annotations

import json
import re
from typing import Any

from fastapi import FastAPI

from grimoire.browser_lane import is_browser_path

_API_PREFIX = "/api/grimoire"
_METHODS = ("get", "post", "put", "patch", "delete")
_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def browser_openapi() -> dict[str, Any]:
    from grimoire import register

    app = FastAPI()
    register(app)
    return app.openapi()


def _name(ref: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", ref.rsplit("/", 1)[-1])


def _key(name: str) -> str:
    return name if _IDENT.match(name) else json.dumps(name)


def _type(schema: dict[str, Any] | bool | None, indent: str = "") -> str:
    if schema is None or schema is True or schema == {}:
        return "unknown"
    if schema is False:
        return "never"
    if "$ref" in schema:
        return _name(schema["$ref"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            parts = [_type(part, indent) for part in schema[union]]
            return " | ".join(dict.fromkeys(parts))
    if "allOf" in schema:
        return " & ".join(_type(part, indent) for part in schema["allOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(_type({**schema, "type": one}, indent) for one in kind)
    if kind == "null":
        return "null"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "string":
        return "Blob" if schema.get("format") == "binary" else "string"
    if kind == "array":
        if "prefixItems" in schema:
            items = ", ".join(_type(item, indent) for item in schema["prefixItems"])
            return f"[{items}]"
        item = _type(schema.get("items"), indent)
        return f"Array<{item}>"
    if kind == "object" or "properties" in schema:
        return _object(schema, indent)
    return "unknown"


def _object(schema: dict[str, Any], indent: str) -> str:
    properties = schema.get("properties") or {}
    extra = schema.get("additionalProperties")
    if not properties:
        if isinstance(extra, dict):
            return f"Record<string, {_type(extra, indent)}>"
        return "Record<string, unknown>"
    required = set(schema.get("required", ()))
    inner = indent + "  "
    lines = [
        f"{inner}{_key(name)}{'' if name in required else '?'}: {_type(value, inner)};"
        for name, value in properties.items()
    ]
    if isinstance(extra, dict):
        lines.append(f"{inner}[key: string]: unknown;")
    return "{\n" + "\n".join(lines) + f"\n{indent}}}"


def _json_schema(content: dict[str, Any] | None) -> dict[str, Any] | None:
    if not content:
        return None
    for media in ("application/json", "multipart/form-data"):
        if media in content:
            return content[media].get("schema")
    return None


def render(spec: dict[str, Any] | None = None) -> str:
    spec = spec or browser_openapi()
    operations = []
    for path, item in sorted(spec["paths"].items()):
        if not is_browser_path(path):
            continue
        for method in _METHODS:
            if method in item:
                operations.append((method.upper(), path, item[method]))

    out = [
        "// Generated by projects/monolith/grimoire/browser_api_schema.py.",
        "// Do not edit: regenerate with the command in that module's docstring.",
        "",
    ]
    schemas = spec.get("components", {}).get("schemas", {})
    used: list[str] = []

    def collect(node: Any) -> None:
        if isinstance(node, dict):
            ref = node.get("$ref")
            if isinstance(ref, str):
                name = ref.rsplit("/", 1)[-1]
                if name not in used and name in schemas:
                    used.append(name)
                    collect(schemas[name])
            for value in node.values():
                collect(value)
        elif isinstance(node, list):
            for value in node:
                collect(value)

    for _method, _path, operation in operations:
        collect(operation)
    for name in sorted(used):
        if name in ("HTTPValidationError", "ValidationError"):
            continue
        schema = schemas[name]
        rendered = _type(schema)
        if rendered.startswith("{"):
            out.append(f"export interface {_name(name)} {rendered}")
        else:
            out.append(f"export type {_name(name)} = {rendered};")
        out.append("")

    out.append("/** One entry per browser-routed operation, keyed `METHOD /path`. */")
    out.append("export interface Operations {")
    for method, path, operation in operations:
        success = next(
            (
                operation["responses"][code]
                for code in ("200", "201", "204")
                if code in operation["responses"]
            ),
            {},
        )
        response = _json_schema(success.get("content"))
        body = _json_schema((operation.get("requestBody") or {}).get("content"))
        query = {
            parameter["name"]: parameter
            for parameter in operation.get("parameters", ())
            if parameter["in"] == "query"
        }
        query_type = (
            "{"
            + " ".join(
                f"{_key(name)}{'' if parameter.get('required') else '?'}: "
                f"{_type(parameter.get('schema'), '    ')};"
                for name, parameter in query.items()
            )
            + "}"
            if query
            else "undefined"
        )
        out.append(f"  {json.dumps(f'{method} {path[len(_API_PREFIX) :]}')}: {{")
        out.append(f"    query: {query_type};")
        out.append(f"    body: {_type(body, '    ') if body else 'undefined'};")
        out.append(
            f"    response: {_type(response, '    ') if response else 'undefined'};"
        )
        out.append("  };")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    print(render(), end="")
